import streamlit as st
import joblib
import pandas as pd


# ---------------------------------------------------
# PAGE CONFIGURATION
# ---------------------------------------------------

st.set_page_config(
    page_title="Diabetes Prediction AI",
    page_icon="🩺",
    layout="centered"
)


# ---------------------------------------------------
# LOAD TRAINED MODEL
# ---------------------------------------------------

model = joblib.load("diabetes_model.pkl")


# ---------------------------------------------------
# HEADER
# ---------------------------------------------------

st.title("🩺 Diabetes Prediction using AI")

st.markdown(
    """
    This application uses a **Machine Learning Decision Tree model**
    to predict the likelihood of diabetes based on patient information.
    """
)

st.divider()


# ---------------------------------------------------
# PATIENT INFORMATION
# ---------------------------------------------------

st.header("👤 Patient Information")

st.write(
    "Please enter the following health-related information:"
)


# Create two columns for a cleaner layout
col1, col2 = st.columns(2)


with col1:

    pregnancies = st.number_input(
        "Pregnancies",
        min_value=0,
        max_value=20,
        value=1,
        help="Number of times the patient has been pregnant."
    )

    glucose = st.number_input(
        "Glucose",
        min_value=0,
        max_value=300,
        value=120,
        help="Plasma glucose concentration."
    )

    blood_pressure = st.number_input(
        "Blood Pressure",
        min_value=0,
        max_value=200,
        value=70,
        help="Diastolic blood pressure."
    )

    skin_thickness = st.number_input(
        "Skin Thickness",
        min_value=0,
        max_value=100,
        value=20,
        help="Triceps skin fold thickness."
    )


with col2:

    insulin = st.number_input(
        "Insulin",
        min_value=0,
        max_value=900,
        value=80,
        help="2-Hour serum insulin level."
    )

    bmi = st.number_input(
        "BMI",
        min_value=0.0,
        max_value=70.0,
        value=25.0,
        step=0.1,
        help="Body Mass Index."
    )

    diabetes_pedigree = st.number_input(
        "Diabetes Pedigree Function",
        min_value=0.0,
        max_value=3.0,
        value=0.5,
        step=0.01,
        help="Diabetes likelihood based on family history."
    )

    age = st.number_input(
        "Age",
        min_value=1,
        max_value=120,
        value=30,
        help="Age of the patient."
    )


st.divider()


# ---------------------------------------------------
# PREDICTION
# ---------------------------------------------------

if st.button(
    "🔍 Predict Diabetes",
    use_container_width=True
):

    # Create input DataFrame
    input_data = pd.DataFrame(
        [[
            pregnancies,
            glucose,
            blood_pressure,
            skin_thickness,
            insulin,
            bmi,
            diabetes_pedigree,
            age
        ]],
        columns=[
            "Pregnancies",
            "Glucose",
            "BloodPressure",
            "SkinThickness",
            "Insulin",
            "BMI",
            "DiabetesPedigreeFunction",
            "Age"
        ]
    )


    # Make prediction
    prediction = model.predict(input_data)[0]


    # Get prediction probability
    probability = model.predict_proba(input_data)[0]


    # ---------------------------------------------------
    # RESULT
    # ---------------------------------------------------

    st.header("📊 Prediction Result")


    if prediction == 1:

        diabetes_probability = probability[1] * 100

        st.error(
            "⚠️ The model predicts a higher likelihood of diabetes."
        )

        st.metric(
            "Estimated Diabetes Probability",
            f"{diabetes_probability:.2f}%"
        )

    else:

        diabetes_probability = probability[1] * 100

        st.success(
            "✅ The model predicts a lower likelihood of diabetes."
        )

        st.metric(
            "Estimated Diabetes Probability",
            f"{diabetes_probability:.2f}%"
        )


    # Show probability bar
    st.write("Diabetes Probability")

    st.progress(
        int(diabetes_probability)
    )


# ---------------------------------------------------
# DISCLAIMER
# ---------------------------------------------------

st.divider()

st.info(
    """
    ℹ️ **Disclaimer:** This application is developed for educational
    and internship project purposes. The prediction is generated by
    a machine learning model and **must not be considered a medical
    diagnosis or a substitute for professional medical advice.**
    """
)


# ---------------------------------------------------
# FOOTER
# ---------------------------------------------------

st.caption(
    "Diabetes Prediction using Machine Learning | Decision Tree Model"
)
